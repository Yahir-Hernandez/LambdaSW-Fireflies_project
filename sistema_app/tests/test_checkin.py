@pytest.mark.django_db
@pytest.mark.integration
class TestAdminCheckinDataEndpoint:
    def test_returns_json_with_reservation_data(self, superuser_client, active_reservation):
        """Superusuario hace GET al endpoint con el token de una reservación activa; verifica el JSON con id, status y can_check_in."""
        url = reverse(
            "admin:sistema_app_reservation_checkin_data",
            args=[active_reservation.checkin_token],
        )
        response = superuser_client.get(url)
        assert response.status_code == 200
        data = response.json()
        assert data["id"] == active_reservation.pk
        assert data["status"] == Reservation.Status.ACTIVE
        assert data["can_check_in"] is True

    def test_unknown_token_returns_404(self, superuser_client):
        """Superusuario hace GET con un UUID que no existe en BD; verifica que responde HTTP 404."""
        url = reverse(
            "admin:sistema_app_reservation_checkin_data",
            args=[uuid.uuid4()],
        )
        response = superuser_client.get(url)
        assert response.status_code == 404

    def test_used_reservation_reports_cannot_checkin(self, superuser_client, active_reservation):
        """Se hace check-in a la reservación y luego se consulta el endpoint; verifica que el JSON indica can_check_in False y status USED."""
        ReservationCheckinService.check_in(active_reservation)
        url = reverse(
            "admin:sistema_app_reservation_checkin_data",
            args=[active_reservation.checkin_token],
        )
        response = superuser_client.get(url)
        data = response.json()
        assert data["can_check_in"] is False
        assert data["status"] == Reservation.Status.USED

    def test_unauthenticated_redirects(self, client, active_reservation):
        """Cliente sin autenticar hace GET al endpoint con token válido; verifica que redirige."""
        url = reverse(
            "admin:sistema_app_reservation_checkin_data",
            args=[active_reservation.checkin_token],
        )
        response = client.get(url)
        assert response.status_code in (302, 301)


@pytest.mark.django_db
@pytest.mark.integration
class TestAdminCheckinConfirmEndpoint:
    def test_confirm_transitions_active_to_used(self, superuser_client, active_reservation):
        """Superusuario hace POST al endpoint de confirmación; verifica HTTP 200, json['ok'] True, status USED en BD."""
        url = reverse(
            "admin:sistema_app_reservation_checkin_confirm",
            args=[active_reservation.checkin_token],
        )
        response = superuser_client.post(url)
        assert response.status_code == 200
        data = response.json()
        assert data["ok"] is True
        assert data["status"] == Reservation.Status.USED
        active_reservation.refresh_from_db()
        assert active_reservation.status == Reservation.Status.USED

    def test_confirm_twice_returns_400(self, superuser_client, active_reservation):
        """Se confirma el check-in dos veces con el mismo token; verifica que la segunda responde HTTP 400 con clave 'error'."""
        url = reverse(
            "admin:sistema_app_reservation_checkin_confirm",
            args=[active_reservation.checkin_token],
        )
        superuser_client.post(url)
        response = superuser_client.post(url)
        assert response.status_code == 400
        assert "error" in response.json()

    def test_confirm_cancelled_returns_400(self, superuser_client, cancelled_reservation):
        """Superusuario hace POST con el token de una reservación cancelada; verifica que responde HTTP 400."""
        url = reverse(
            "admin:sistema_app_reservation_checkin_confirm",
            args=[cancelled_reservation.checkin_token],
        )
        response = superuser_client.post(url)
        assert response.status_code == 400

    def test_get_not_allowed(self, superuser_client, active_reservation):
        """Superusuario hace GET en lugar de POST al endpoint de confirmación; verifica que responde HTTP 405."""
        url = reverse(
            "admin:sistema_app_reservation_checkin_confirm",
            args=[active_reservation.checkin_token],
        )
        response = superuser_client.get(url)
        assert response.status_code == 405

    def test_unknown_token_returns_404(self, superuser_client):
        """Superusuario hace POST con un UUID que no existe; verifica que responde HTTP 404."""
        url = reverse(
            "admin:sistema_app_reservation_checkin_confirm",
            args=[uuid.uuid4()],
        )
        response = superuser_client.post(url)
        assert response.status_code == 404
