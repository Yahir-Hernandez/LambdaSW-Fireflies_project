@pytest.mark.django_db
class TestReservationCheckinToken:
    def test_token_autogenerated(self, active_reservation):
        """Accede al campo checkin_token de una reservación recién creada; verifica que existe y es uuid.UUID."""
        assert active_reservation.checkin_token is not None
        assert isinstance(active_reservation.checkin_token, uuid.UUID)

    def test_tokens_are_unique(self, db, user, park, cabin, camping_spot, season_start, season_end_date):
        """Crea dos reservaciones distintas y compara sus checkin_token; verifica que son diferentes entre sí."""
        r1 = Reservation.objects.create(
            user=user, park=park, lodging=cabin,
            start_date=season_start, end_date=season_end_date, people=1,
        )
        r2 = Reservation.objects.create(
            user=user, park=park, lodging=camping_spot,
            start_date=season_start, end_date=season_end_date, people=1,
        )
        assert r1.checkin_token != r2.checkin_token


@pytest.mark.django_db
class TestReservationMarkAsUsed:
    def test_mark_as_used_changes_status(self, active_reservation):
        """Llama mark_as_used() sobre una reservación activa y recarga desde BD; verifica que el status cambia a USED."""
        active_reservation.mark_as_used()
        active_reservation.refresh_from_db()
        assert active_reservation.status == Reservation.Status.USED

    def test_mark_as_used_on_cancelled_raises(self, cancelled_reservation):
        """Llama mark_as_used() sobre una reservación cancelada; verifica que lanza ValidationError."""
        with pytest.raises(ValidationError):
            cancelled_reservation.mark_as_used()

    def test_mark_as_used_on_past_raises(self, past_reservation):
        """Llama mark_as_used() sobre una reservación con status PAST; verifica que lanza ValidationError."""
        with pytest.raises(ValidationError):
            past_reservation.mark_as_used()

    def test_mark_as_used_on_used_raises(self, active_reservation):
        """Llama mark_as_used() dos veces sobre la misma reservación; verifica que la segunda llamada lanza ValidationError."""
        active_reservation.mark_as_used()
        active_reservation.refresh_from_db()
        with pytest.raises(ValidationError):
            active_reservation.mark_as_used()


